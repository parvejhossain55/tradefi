function createTimestamps() {
  const now = Date.now();
  return {
    minutesAgo: (minutes: number) => new Date(now - minutes * 60_000).toISOString(),
    hoursAgo: (hours: number) => new Date(now - hours * 3_600_000).toISOString(),
    daysAgo: (days: number) => new Date(now - days * 86_400_000).toISOString(),
  };
}

