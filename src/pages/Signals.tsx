import { Card, CardHeader } from '@/components/ui/Card';
import { PageHeader } from '@/components/ui/PageHeader';
import { StatCard } from '@/components/ui/StatCard';
import { SignalHistoryTable } from '@/components/signals/SignalHistoryTable';
import { useTradingStore } from '@/store/tradingStore';

export function Signals() {
  const snapshot = useTradingStore((state) => state.snapshot);
  if (!snapshot) return null;

  const signals = snapshot.signals;
  const last24h = signals.filter(
    (signal) => Date.now() - new Date(signal.timestamp).getTime() < 86_400_000
  ).length;

  return (
    <div>
      <PageHeader
        title="Signals & Events"
        description="Inspect simulated signal records generated by the local demo model. This workspace has no live market feed and no execution engine."
      />

      <div className="grid grid-cols-2 gap-3 lg:grid-cols-4">
        <StatCard
          label="Total signals"
          value={signals.length}
          hint="All demo records"
          icon="signals"
          tone="primary"
        />
        <StatCard
          label="Simulated"
          value={signals.filter((signal) => signal.status === 'simulated').length}
          hint="Eligible demo signal records"
          icon="checkCircle"
          tone="primary"
        />
        <StatCard
          label="Filtered"
          value={signals.filter((signal) => signal.status === 'filtered').length}
          hint="Blocked by configured rules"
          icon="filter"
          tone="warning"
        />
        <StatCard
          label="Last 24 hours"
          value={last24h}
          hint="Rolling window"
          icon="clock"
          tone="neutral"
        />
      </div>

      <Card className="mt-4">
        <CardHeader
          title="Signal history"
          description="Filter by pair, strategy, type, status, or date range. Open a row for full event details."
        />
        <SignalHistoryTable
          signals={signals}
          pairs={snapshot.pairs}
          strategies={snapshot.strategies}
          showPairFilter
          pageSize={10}
        />
      </Card>
    </div>
  );
}
